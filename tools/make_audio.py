#!/usr/bin/env python3
"""Pre-render the Spanish words to WAV files.

Why this exists: the browser's speech synthesis needs a voice installed by the
operating system, and plenty of machines have none — the app then "says" the
word into silence. Rendering the audio once, here, removes that dependency
entirely: the demo plays plain WAV files and needs no voices at runtime.

Standard library only (ctypes + wave). It borrows libespeak-ng if it happens to
be installed, so it is a build-time tool, not a runtime dependency of the app.

    python3 tools/make_audio.py

Writes assets/audio/<slug>.wav and assets/audio/manifest.js.
"""

import ctypes
import json
import os
import pathlib
import re
import sys
import unicodedata
import wave

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "audio"
DATA = ROOT / "src" / "data.js"

AUDIO_OUTPUT_SYNCHRONOUS = 2
ESP_RATE, ESP_VOLUME = 1, 2

CANDIDATES = [
    "/usr/lib/aarch64-linux-gnu/libespeak-ng.so.1",
    "/usr/lib/x86_64-linux-gnu/libespeak-ng.so.1",
    "libespeak-ng.so.1",
]


def load_lib():
    for path in CANDIDATES:
        try:
            return ctypes.CDLL(path)
        except OSError:
            continue
    sys.exit("make_audio: libespeak-ng not found — this tool needs it, the app does not.")


def slug(text):
    """ASCII-safe file name: montaña -> montana."""
    folded = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")


def concepts():
    """Read id/article/word out of the dataset without a JS parser."""
    src = DATA.read_text(encoding="utf-8")
    pattern = re.compile(
        r'id:\s*"([^"]+)"[^}]*?word:\s*"([^"]+)"[^}]*?article:\s*"([^"]*)"', re.S
    )
    out = []
    for m in pattern.finditer(src):
        cid, word, article = m.group(1), m.group(2), m.group(3)
        out.append((cid, word, article))
    return out


def trim(samples, threshold=260, pad=0.03, rate=22050):
    first, last = 0, len(samples) - 1
    while first < last and abs(samples[first]) < threshold:
        first += 1
    while last > first and abs(samples[last]) < threshold:
        last -= 1
    pad_n = int(rate * pad)
    return samples[max(0, first - pad_n): min(len(samples), last + pad_n)]


def downsample(samples):
    """22050 -> 11025 by averaging pairs; halves the file with no audible loss
    at speech bandwidth, and these files are committed to the repo."""
    return [
        (samples[i] + samples[i + 1]) // 2
        for i in range(0, len(samples) - 1, 2)
    ]


def main():
    lib = load_lib()
    lib.espeak_Initialize.restype = ctypes.c_int
    lib.espeak_Initialize.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_char_p, ctypes.c_int]

    rate = lib.espeak_Initialize(AUDIO_OUTPUT_SYNCHRONOUS, 0, None, 0)
    if rate <= 0:
        sys.exit("make_audio: espeak could not start")

    buffer = []

    CB = ctypes.CFUNCTYPE(ctypes.c_int, ctypes.POINTER(ctypes.c_short), ctypes.c_int, ctypes.c_void_p)

    def callback(wav, count, _event):
        if count > 0:
            buffer.extend(wav[:count])
        return 0

    keep_alive = CB(callback)
    lib.espeak_SetSynthCallback(keep_alive)

    lib.espeak_SetVoiceByName.argtypes = [ctypes.c_char_p]
    if lib.espeak_SetVoiceByName(b"es") != 0:
        sys.exit("make_audio: no Spanish voice in espeak")

    lib.espeak_SetParameter(ESP_RATE, 140, 0)
    lib.espeak_SetParameter(ESP_VOLUME, 110, 0)

    lib.espeak_Synth.argtypes = [
        ctypes.c_void_p, ctypes.c_size_t, ctypes.c_uint, ctypes.c_int,
        ctypes.c_uint, ctypes.c_uint, ctypes.POINTER(ctypes.c_uint), ctypes.c_void_p,
    ]

    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    total = 0

    for cid, word, article in concepts():
        spoken = ("%s %s" % (article, word)) if article else word
        buffer.clear()
        raw = spoken.encode("utf-8")
        lib.espeak_Synth(raw, len(raw) + 1, 0, 1, 0, 1, None, None)
        lib.espeak_Synchronize()

        samples = trim(buffer, rate=rate)
        samples = downsample(samples)
        if not samples:
            print("  ! empty audio for", cid)
            continue

        name = slug(cid) + ".wav"
        path = OUT / name
        with wave.open(str(path), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(rate // 2)
            w.writeframes(b"".join(int(s).to_bytes(2, "little", signed=True) for s in samples))

        manifest[cid] = "assets/audio/" + name
        total += path.stat().st_size
        print("  %-10s %5d bytes  %s" % (cid, path.stat().st_size, spoken))

    (OUT / "manifest.js").write_text(
        "/* generated by tools/make_audio.py — do not edit by hand */\n"
        "window.SEMA_AUDIO = " + json.dumps(manifest, ensure_ascii=False, indent=0).replace("\n", "") + ";\n",
        encoding="utf-8",
    )

    print("\n%d files, %.0f KB total" % (len(manifest), total / 1024))


if __name__ == "__main__":
    main()
